/*
 * Measures WCAG 2.1 contrast for every colour pair the application actually renders, in
 * both themes, straight out of apps/web/src/styles/tokens.css.
 *
 * The design kit states its own ratios on tokens-board.html. This recomputes them rather
 * than transcribing them: ground-truth/README.md's rule is that a hand-written doc may not
 * state a number a generated report does not confirm, and an accessibility claim nobody
 * checked is the kind that survives until someone cannot read the page.
 *
 *   npm run contrast
 */

import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/paths.js';

const TOKENS = path.join(ROOT, 'apps/web/src/styles/tokens.css');
const REPORT = path.join(ROOT, 'ground-truth/reports/token-contrast.md');

// Foreground, background, where it is used, and the threshold that applies. Body text and
// anything under 18.66px bold needs 4.5; large text and UI borders need 3.
const PAIRS = [
  ['--text', '--bg', 'body text on the page', 4.5],
  ['--text', '--surface', 'body text on a card', 4.5],
  ['--text', '--surface2', 'body text on a raised row', 4.5],
  ['--muted', '--bg', 'secondary text on the page', 4.5],
  ['--muted', '--surface', 'secondary text on a card', 4.5],
  ['--faint', '--surface', 'raw tokens in mono under a biome label', 4.5],
  ['--faint', '--bg', 'placeholder text', 4.5],
  ['--link', '--bg', 'inline links', 4.5],
  ['--link-hover', '--bg', 'hovered links', 4.5],
  ['--cta-text', '--cta', 'the Discord button label', 4.5],
  ['--danger', '--danger-bg', 'error panel text', 4.5],
  ['--danger', '--bg', 'error text on the page', 4.5],
  ['--line-strong', '--bg', 'title-block rules', 3],
  ['--focus', '--bg', 'the focus ring', 3],
  ['--t-common-fg', '--t-common-bg', 'common bucket chip', 4.5],
  ['--t-uncommon-fg', '--t-uncommon-bg', 'uncommon bucket chip', 4.5],
  ['--t-rare-fg', '--t-rare-bg', 'rare bucket chip', 4.5],
  ['--t-ultra-fg', '--t-ultra-bg', 'ultra-rare bucket chip', 4.5],
  ['--t-legendary-fg', '--t-legendary-bg', 'legendary bucket chip', 4.5],
];

function parseBlock(css, header) {
  const start = css.indexOf(header);
  if (start === -1) return null;
  const open = css.indexOf('{', start);
  let depth = 0;
  let i = open;
  for (; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) break;
  }
  const body = css.slice(open + 1, i);
  const out = {};
  for (const m of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

const hex = (v) => {
  const m = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(v.trim());
  if (!m) return null;
  const h = m[1].length === 3 ? m[1].split('').map((c) => c + c).join('') : m[1];
  return [0, 2, 4].map((o) => parseInt(h.slice(o, o + 2), 16));
};

const luminance = ([r, g, b]) => {
  const f = (c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
};

const contrast = (a, b) => {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
};

function main() {
  const css = fs.readFileSync(TOKENS, 'utf8');
  const light = parseBlock(css, ':root {');
  const dark = parseBlock(css, ':root[data-theme="dark"]');
  if (!light || !dark) {
    console.error('[fail] could not find both the :root and :root[data-theme="dark"] blocks');
    process.exit(1);
  }

  const themes = [['Light', light], ['Dark', { ...light, ...dark }]];
  const rows = [];
  let failures = 0;
  let skipped = 0;

  for (const [name, tokens] of themes) {
    for (const [fg, bg, use, threshold] of PAIRS) {
      const a = hex(tokens[fg] ?? '');
      const b = hex(tokens[bg] ?? '');
      if (!a || !b) { skipped++; continue; }
      const ratio = contrast(a, b);
      const pass = ratio >= threshold;
      if (!pass) failures++;
      rows.push({ name, fg, bg, use, threshold, ratio, pass });
    }
  }

  const table = (theme) => [
    '| Foreground | Background | Used for | Needs | Measured | |',
    '|---|---|---|---|---|---|',
    ...rows.filter((r) => r.name === theme).map((r) =>
      `| \`${r.fg}\` | \`${r.bg}\` | ${r.use} | ${r.threshold.toFixed(1)}:1 | ` +
      `${r.ratio.toFixed(2)}:1 | ${r.pass ? '[pass]' : '[FAIL]'} |`),
  ].join('\n');

  const md = `# Token contrast

Generated by \`npm run contrast\` (\`scripts/check-contrast.js\`) from
\`apps/web/src/styles/tokens.css\`. Do not hand-edit.

WCAG 2.1 contrast, computed from the token hexes themselves. ${rows.length} pairs checked
across both themes, ${failures} failing. A pair needing 4.5:1 carries body text; a pair
needing 3:1 is a rule, a border or a focus ring, never text.

The kit states its own ratios on \`design/artboards/tokens-board.html\`. These are
recomputed rather than copied, because a contrast claim nobody checked is exactly the kind
that survives to launch.

## Light

${table('Light')}

## Dark

${table('Dark')}
${skipped ? `\n${skipped} pair(s) skipped: the token is not a plain hex.\n` : ''}`;

  fs.mkdirSync(path.dirname(REPORT), { recursive: true });
  fs.writeFileSync(REPORT, md, 'utf8');

  for (const r of rows.filter((x) => !x.pass)) {
    console.error(`[FAIL] ${r.name}: ${r.fg} on ${r.bg} is ${r.ratio.toFixed(2)}:1, needs ${r.threshold}:1 (${r.use})`);
  }
  console.log(`[ok] ${path.relative(ROOT, REPORT)}  ${rows.length} pairs, ${failures} failing`);
  process.exit(failures ? 1 : 0);
}

main();
