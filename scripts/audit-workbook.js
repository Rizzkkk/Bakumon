import fs from 'node:fs/promises';
import path from 'node:path';
import {
  ROOT, loadWorkbook, parseSelector, expandSpawnRow, toCategory,
} from './lib/workbook.js';

const OUT = path.join(ROOT, 'ground-truth/reports/workbook-audit.md');

function tally(values) {
  const counts = new Map();
  for (const value of values) counts.set(value, (counts.get(value) ?? 0) + 1);
  return [...counts.entries()].sort((a, b) => b[1] - a[1]);
}

function table(header, rows) {
  return [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

const wb = await loadWorkbook();

const spawns = wb.pokemonRows.flatMap(expandSpawnRow);
const species = new Map();
for (const row of wb.pokemonRows) {
  const { species: slug } = parseSelector(row.selector);
  if (!species.has(slug)) species.set(slug, []);
  species.get(slug).push(row);
}

// Seven species appear under two spellings in adjacent rows (`hakamo_o` / `hakamoo`).
// Collapsing separators finds them without hardcoding the list, so a future workbook that
// fixes them - or introduces more - is reported accurately.
const spellingGroups = new Map();
for (const slug of species.keys()) {
  const key = slug.replace(/[_-]/g, '');
  if (!spellingGroups.has(key)) spellingGroups.set(key, []);
  spellingGroups.get(key).push(slug);
}
const duplicateSpellings = [...spellingGroups.values()].filter((g) => g.length > 1);

const aspectKeys = tally(
  wb.pokemonRows.flatMap((r) => Object.keys(parseSelector(r.selector).aspects)),
);
const biomeTokens = tally(spawns.flatMap((s) => s.biomes));
const namespaces = tally(
  biomeTokens.flatMap(([token, n]) => Array(n).fill(token.replace(/^#/, '').split(':')[0])),
);
const flaggedRows = wb.pokemonRows.filter((r) => expandSpawnRow(r).some((s) => s.parseFlag));

const categories = tally(wb.itemRows.map((r) => toCategory(r.wikiCategory)));
const sourceCategories = tally(wb.itemRows.map((r) => r.sourceCategory));
const evolutionCounts = tally(wb.itemRows.map((r) => r.usedInEvolutions || '(blank)'));

const masterIds = new Set(wb.itemRows.map((r) => r.itemId));
const orphans = [];
for (const [sheet, rows] of Object.entries(wb.subsets)) {
  for (const row of rows) if (!masterIds.has(row.itemId)) orphans.push([sheet, row.itemId]);
}

const blankDesc = wb.itemRows.filter((r) => !r.description.trim()).length;
const thinDesc = wb.itemRows.filter((r) => r.description.trim() && r.description.length < 40).length;
const langKeys = wb.itemRows.filter((r) => r.itemId.split(':')[1]?.includes('.'));

const report = `# Workbook audit

Generated by \`npm run audit\` (\`scripts/audit-workbook.js\`) on ${new Date().toISOString().slice(0, 10)}.
**Do not hand-edit.** Source: \`Cobblemon_Full_Pokemon_Wiki_No_Legendary.xlsx\`.

Every number in \`ground-truth/\` that describes the workbook should match this file.

## Headline counts

${table(['Measure', 'Value'], [
  ['Rows on `Pokemon Wiki` (excluding header)', wb.allPokemonRows.length],
  ['Spawn-definition rows', wb.pokemonRows.length],
  ['Distinct species', species.size],
  ['Rows carrying form aspects', wb.pokemonRows.filter((r) => r.selector.includes(' ')).length],
  ['Expanded `pokemon_spawns` rows', spawns.length],
  ['Source rows needing a padded field', `${flaggedRows.length} (${Math.round(flaggedRows.length / wb.pokemonRows.length * 100)}%)`],
  ['Prose note rows excluded from import', wb.serverNotes.length],
  ['Rows on `Item Wiki`', wb.itemRows.length],
  ['Distinct item IDs', new Set(wb.itemRows.map((r) => r.itemId)).size],
])}

The expanded spawn count exceeds the sum of the \`Spawn Entries\` column (2,995) because
that column undercounts for 144 rows. Aerodactyl declares 1 entry but carries two weights
(\`10; 0.1\`) - two real spawn entries. Taking the widest field array keeps both.

## Species and forms

${table(['Measure', 'Value'], [
  ['Species appearing only as a form', species.size - new Set(wb.pokemonRows.filter((r) => !r.selector.includes(' ')).map((r) => r.selector)).size],
  ['Species with the most form rows', [...species.entries()].sort((a, b) => b[1].length - a[1].length).slice(0, 4).map(([s, r]) => `${s} (${r.length})`).join(', ')],
])}

Species present **only** as form rows, which a species list built from plain rows alone
would lose: ${[...species.keys()].filter((s) => !wb.pokemonRows.some((r) => r.selector === s)).map((s) => `\`${s}\``).join(', ')}.

### Species spelled more than one way

${duplicateSpellings.length} species carry two spellings in the workbook, each with its own
spawn configuration. The distinct-species count above therefore overstates the real number
of Pokemon by ${duplicateSpellings.reduce((a, g) => a + g.length - 1, 0)}: **${species.size - duplicateSpellings.reduce((a, g) => a + g.length - 1, 0)}** distinct Pokemon.

${table(['Spellings', 'Rows in the sheet'], duplicateSpellings.map((g) => [
  g.map((s) => `\`${s}\``).join(' / '),
  g.map((s) => species.get(s).map((r) => r.rawRowIndex).join(', ')).join(' / '),
]))}

Aspect keys in use:

${table(['Aspect key', 'Rows'], aspectKeys.map(([k, n]) => [`\`${k}\``, n]))}

## Spawn buckets

${table(['Bucket', 'Spawn rows'], tally(spawns.map((s) => s.bucket ?? '(none)')).map(([k, n]) => [`\`${k}\``, n]))}

## Spawn contexts

${table(['Context', 'Spawn rows'], tally(spawns.map((s) => s.context ?? '(none)')).map(([k, n]) => [`\`${k}\``, n]))}

## Biomes

${biomeTokens.length} distinct tokens across ${biomeTokens.reduce((a, [, n]) => a + n, 0)} references.
Tags (\`#\`-prefixed) are sets of biomes, not biomes; a filter matching concrete biome
names alone misses most of the dex.

${table(['Namespace', 'References'], namespaces.map(([k, n]) => [`\`${k}\``, n]))}

${table(['Kind', 'Tokens'], [
  ['Tags (`#`-prefixed)', biomeTokens.filter(([t]) => t.startsWith('#')).length],
  ['Concrete biomes', biomeTokens.filter(([t]) => !t.startsWith('#')).length],
])}

## Items

Canonical category, derived from \`Wiki Category\` via the explicit map in
\`scripts/lib/workbook.js\`. These totals must reconcile to ${wb.itemRows.length}:

${table(['Category', 'Items'], categories.map(([k, n]) => [`\`${k}\``, n]))}

The \`Item Categories\` sheet independently states:

${table(['Category', 'Stated count'], wb.itemCategories.map((r) => [r.category, r.count]))}

\`Source Category\` is the second axis, and the only place berries, fossils and Poke Balls
are distinguishable:

${table(['Source category', 'Items'], sourceCategories.map(([k, n]) => [k || '(blank)', n]))}

\`Used in Evolutions\` is a count, not a boolean:

${table(['Value', 'Items'], evolutionCounts.map(([k, n]) => [`\`${k}\``, n]))}

## Coverage gaps

${table(['Gap', 'Count'], [
  ['Items with a blank description', `${blankDesc} (${Math.round(blankDesc / wb.itemRows.length * 100)}%)`],
  ['Items with a description under 40 characters', thinDesc],
  ['Item IDs on a subset sheet but absent from `Item Wiki`', orphans.length],
  ['Item IDs that look like localisation keys', langKeys.length],
])}

${orphans.length ? `Orphans: ${orphans.map(([s, id]) => `\`${id}\` (${s})`).join(', ')}.` : 'No orphans.'}

Localisation-key rows, which are lang fragments rather than items:
${langKeys.map((r) => `\`${r.itemId}\``).join(', ')}.

## Subset sheet reconciliation

${table(['Sheet', 'Rows', 'Resolve against Item Wiki'], Object.entries(wb.subsets).map(([sheet, rows]) => [
  sheet, rows.length, rows.every((r) => masterIds.has(r.itemId)) ? 'all' : `${rows.filter((r) => !masterIds.has(r.itemId)).length} missing`,
]))}

## Server notes transcribed from the sheet

The bottom of \`Pokemon Wiki\` carries a prose block describing how this server's spawn
tiers work. It is excluded from import and reproduced in
\`ground-truth/01-data/server-notes.md\`.

${wb.serverNotes.map((n) => `- **${n.heading}**${n.body ? ` - ${n.body}` : ''}`).join('\n')}
`;

await fs.writeFile(OUT, report, 'utf8');

console.log(`[done] ${path.relative(ROOT, OUT)}`);
console.log(`  spawn-definition rows : ${wb.pokemonRows.length}`);
console.log(`  distinct species      : ${species.size}`);
console.log(`  form rows             : ${wb.pokemonRows.filter((r) => r.selector.includes(' ')).length}`);
console.log(`  expanded spawns       : ${spawns.length}`);
console.log(`  items                 : ${wb.itemRows.length}`);
console.log(`  categories            : ${categories.map(([k, n]) => `${k}=${n}`).join(' ')}`);
